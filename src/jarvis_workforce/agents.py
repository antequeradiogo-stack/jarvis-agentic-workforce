"""Deterministic mock agents (no LLM). Each agent only acts through ``ctx.call`` (gate-checked) and returns a
plain dict, which the orchestrator validates as untrusted output."""
from __future__ import annotations
import re


def _words(s: str) -> set:
    return set(re.findall(r"[a-z]{4,}", s.lower()))


class MockResearcher:
    name = "researcher"
    output_kind = "research"

    def run(self, task, ctx, inputs: dict) -> dict:
        docs = ctx.call("list_docs", {})
        goal = _words(task.goal)
        ranked = sorted(docs, key=lambda d: (-len(goal & _words(d.replace("-", " "))), d))
        picked, findings = [], []
        for name in ranked:
            text = ctx.call("read_doc", {"name": name})
            if not goal & _words(text):
                continue
            findings.append((name, ctx.call("summarize", {"text": text, "max_sentences": 2, "focus": task.goal})))
            picked.append(name)
            if len(picked) == 3:
                break
        content = "\n".join(f"- ({n}) {s}" for n, s in findings) or "- No relevant documents found."
        return {"agent": self.name, "kind": "research", "content": content, "sources": picked}


class MockWriter:
    name = "writer"
    output_kind = "draft"

    def run(self, task, ctx, inputs: dict) -> dict:
        research = inputs["research"]
        lines = [f"# Draft report: {task.task_id}", "", f"**Goal:** {task.goal}", "", "## Findings", research.content,
                 "", "## Sources", *[f"- {s}" for s in research.sources], "",
                 "_Generated by deterministic mock agents from a synthetic corpus._"]
        return {"agent": self.name, "kind": "draft", "content": "\n".join(lines), "sources": list(research.sources)}


class ScriptedAgent:
    """Test/demo helper: returns scripted (possibly malformed) outputs first, then delegates to a real agent."""

    def __init__(self, inner, scripted: list):
        self.inner, self.scripted = inner, list(scripted)
        self.name, self.output_kind = inner.name, inner.output_kind

    def run(self, task, ctx, inputs: dict):
        if self.scripted:
            item = self.scripted.pop(0)
            if isinstance(item, BaseException):
                raise item
            return item
        return self.inner.run(task, ctx, inputs)
